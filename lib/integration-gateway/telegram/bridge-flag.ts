/**
 * Флаг Telegram Chat Bridge — A7 §1.9 / DEC-031 (подписан 11.08.2026).
 *
 * Выключен по умолчанию: отсутствие переменной означает «закрыто», а не
 * «неизвестно». Сравнение со строкой `"true"` буквально — тот же приём, что у
 * модулей 2, 3 и 4; `"1"`, `"TRUE"` и `"yes"` читаются как «выключено», потому
 * что самый вероятный способ включить мост по ошибке — именно они.
 *
 * ВАЖНО про границы. Флаг закрывает ОДНУ из двух границ — приложение.
 * Вторая граница — база: системные RPC моста выданы только `service_role`, и
 * человеческая сессия до них не достаёт ни при каком значении флага
 * (`20260811050000`). Один флаг без этого описывал бы запрет, а не создавал
 * его, — урок guardrail'ов M3 и M4, где сплошной revoke по схеме пропустил
 * командные RPC, жившие в чужой схеме.
 *
 * Что значит «выключен»: мост не принимает обновления, не классифицирует их и
 * не отправляет уведомлений. Не «принимает и молчит» — не принимает вовсе.
 */

export function isTelegramBridgeEnabled(
  value = process.env.REMHAOS_TELEGRAM_BRIDGE_ENABLED,
): boolean {
  return value === "true";
}

/**
 * Причина отказа при выключенном мосте. Одна на все поверхности: сказать
 * «недоступно» без причины — значит заставить человека гадать, а сказать
 * «нет прав» — соврать, потому что дело не в правах.
 */
export const TELEGRAM_BRIDGE_DISABLED_REASON = "bridge_disabled" as const;
