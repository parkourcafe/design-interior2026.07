/**
 * Флаг модуля 3 «Документация» (A5 §4.2.2).
 *
 * Выключен по умолчанию: пока владелец не включит его явно, поверхности
 * модуля — секции рабочего пространства и его команды — не существуют для
 * пользователя. Флаг серверный: решение принимается на сервере и не
 * передаётся в браузер как переключатель, иначе его можно было бы обойти
 * из клиента.
 *
 * У модуля нет собственного дерева маршрутов (он живёт внутри рабочего
 * пространства проекта), поэтому флаг закрывает поверхности, а не страницы.
 * Если поверхности понадобится отдельный URL, он получит ту же проверку и
 * будет отдавать 404 при выключенном флаге.
 */
export function isDocumentationModuleEnabled(
  value = process.env.REMHAOS_DOCUMENTATION_ENABLED,
): boolean {
  return value === "true";
}

